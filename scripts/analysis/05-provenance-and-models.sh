#!/usr/bin/env bash
# =============================================================================
# 05-provenance-and-models.sh
# =============================================================================
# Records the ORIGIN and HISTORY of every analysed file:
#   * which repository it came from
#   * for human files: the historical evidence that it predates the LLM era
#     (commit/date evidence captured during mining)
#   * for LLM files: which model generated it (Claude / ChatGPT / GPT / ...)
#     where that attribution is available.
#
# Attribution availability differs by dataset (we never invent it):
#   gnu : full manifest with repo + evidence (incl. generating model)
#   ci  : repo from filename (both cohorts); LLM markers name no model
#   git : owner/repo parsed from filename; LLM model not recorded at mining time
#
# Inputs  : corpus/gnu/mining-manifest.csv
#           corpus/{ci,git}/{human,llm}/   (filenames carry provenance)
# Outputs : results/analysis/a5_provenance.csv   (one row per file)
#               dataset,population,file,repo,model,history_evidence
#           results/analysis/a5_model_summary.csv (LLM model counts per dataset)
#           results/analysis/a5_repo_summary.csv   (files per repo, top first)
# =============================================================================
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE="$(cd "$HERE/../.." && pwd)"
AN="$BASE/results/analysis"
PROV="$AN/a5_provenance.csv"

echo "dataset,population,file,repo,model,history_evidence" > "$PROV"

# --- normalise a free-text "generated by X" string into a model family --------
normalise_model() {
    local e; e="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
    case "$e" in
        *claude*)  echo "Claude" ;;
        *chatgpt*) echo "ChatGPT" ;;
        *gpt*)     echo "GPT" ;;
        *gemini*)  echo "Gemini" ;;
        *copilot*) echo "Copilot" ;;
        *)         echo "AI-unspecified" ;;
    esac
}

# --- GNU: rich manifest -------------------------------------------------------
# columns: file,provenance,repo,path,evidence   (evidence may be quoted)
tail -n +2 "$BASE/corpus/gnu/mining-manifest.csv" | while IFS= read -r line; do
    file="$(cut -d, -f1 <<<"$line")"
    pop="$(cut -d, -f2 <<<"$line")"
    repo="$(cut -d, -f3 <<<"$line")"
    evidence="$(cut -d, -f5- <<<"$line" | sed 's/^"//; s/"$//')"
    if [ "$pop" = "llm" ]; then
        model="$(normalise_model "$evidence")"
    else
        model="n/a"
    fi
    echo "gnu,$pop,$file,$repo,$model,$evidence"
done >> "$PROV"

# --- CI: provenance from filename ---------------------------------------------
# both cohorts: "<owner>_<repo>__<path>" (see corpus/ci/mining-manifest.csv)
for f in "$BASE"/corpus/ci/human/*; do
    [ -e "$f" ] || continue
    b="$(basename "$f")"; repo="${b%%__*}"
    echo "ci,human,$b,$repo,n/a,mined_real_repo"
done >> "$PROV"
for f in "$BASE"/corpus/ci/llm/*; do
    [ -e "$f" ] || continue
    b="$(basename "$f")"; repo="${b%%__*}"
    echo "ci,llm,$b,$repo,AI-unspecified,explicit_ai_marker"
done >> "$PROV"

# --- GIT: parse owner/repo from filename --------------------------------------
# pattern: "<pop>_<owner>__<repo>__<path>"  (double-underscore separated).
# Fallback when only single underscores: take 2nd and 3rd tokens.
for pop in human llm; do
    for f in "$BASE"/corpus/git/$pop/*; do
        [ -e "$f" ] || continue
        b="$(basename "$f")"
        rest="${b#${pop}_}"
        if [[ "$rest" == *"__"* ]]; then
            owner="${rest%%__*}"; tmp="${rest#*__}"; reponame="${tmp%%__*}"
            repo="$owner/$reponame"
        else
            owner="$(cut -d_ -f1 <<<"$rest")"; reponame="$(cut -d_ -f2 <<<"$rest")"
            repo="$owner/$reponame"
        fi
        if [ "$pop" = "llm" ]; then model="AI-unspecified"; else model="n/a"; fi
        echo "git,$pop,$b,$repo,$model,mined_repo"
    done >> "$PROV"
done

# --- summaries ----------------------------------------------------------------
{
    echo "dataset,model,files"
    tail -n +2 "$PROV" | awk -F',' '$2=="llm"{c[$1","$5]++}
        END{for(k in c) print k","c[k]}' | sort
} > "$AN/a5_model_summary.csv"

{
    echo "dataset,population,repo,files"
    tail -n +2 "$PROV" | awk -F',' '{c[$1","$2","$4]++}
        END{for(k in c) print k","c[k]}' | sort -t, -k4,4nr
} > "$AN/a5_repo_summary.csv"

echo "Wrote $PROV"
echo "Wrote $AN/a5_model_summary.csv"
echo "Wrote $AN/a5_repo_summary.csv"
echo
echo "================= LLM MODEL ATTRIBUTION ================="
column -t -s',' "$AN/a5_model_summary.csv"
echo
echo "Files per dataset/population:"
tail -n +2 "$PROV" | awk -F',' '{c[$1" "$2]++} END{for(k in c) print "  "k": "c[k]}' | sort
echo
echo "Top 8 source repositories overall:"
tail -n +2 "$AN/a5_repo_summary.csv" | head -8 | column -t -s',' || true
